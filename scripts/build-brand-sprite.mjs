// Builds assets/icons/brands.svg, the monochrome tool-logo sprite used by the
// homepage highway's event tags, from the Simple Icons package (CC0-1.0).
//
// Usage (simple-icons is not a site dependency, so point at any install):
//   npm i --prefix /tmp/si simple-icons@16.32.0
//   node scripts/build-brand-sprite.mjs /tmp/si/node_modules/simple-icons
//
// Only glyphs named in data/brands.json are copied. Brands whose owners had
// their marks removed from Simple Icons carry "glyph": null there and render
// as a typeset name only; never draw a stand-in logo for them.

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const REGISTRY = join(ROOT, 'data', 'brands.json');
const OUT = join(ROOT, 'assets', 'icons', 'brands.svg');

function fail(message) {
  console.error(`build-brand-sprite: ${message}`);
  process.exit(1);
}

function readPath(pkgDir, slug) {
  let svg;
  try {
    svg = readFileSync(join(pkgDir, 'icons', `${slug}.svg`), 'utf8');
  } catch (err) {
    fail(`no icon "${slug}" in ${pkgDir}/icons (${err.code})`);
  }
  const match = svg.match(/<path d="([^"]+)"/);
  if (!match) fail(`could not read a path from ${slug}.svg`);
  return match[1];
}

function main() {
  const pkgDir = process.argv[2];
  if (!pkgDir) fail('pass the simple-icons package directory as the first argument');
  const pkg = JSON.parse(readFileSync(join(pkgDir, 'package.json'), 'utf8'));
  if (pkg.name !== 'simple-icons') fail(`${pkgDir} is not the simple-icons package`);

  const registry = JSON.parse(readFileSync(REGISTRY, 'utf8'));
  const glyphs = [...new Set(Object.values(registry).map((b) => b.glyph).filter(Boolean))].sort();
  const symbols = glyphs.map((slug) => `<symbol id="b-${slug}" viewBox="0 0 24 24"><path d="${readPath(pkgDir, slug)}"/></symbol>`);

  const header = `<!-- Tool logos from Simple Icons ${pkg.version} (simpleicons.org), ${pkg.license}. `
    + 'Shown only to name software the agents can work with. The marks belong to their owners; '
    + 'no partnership, sponsorship or endorsement is implied. Generated by scripts/build-brand-sprite.mjs. -->';
  const out = `<svg xmlns="http://www.w3.org/2000/svg">${header}\n${symbols.join('\n')}\n</svg>\n`;

  mkdirSync(dirname(OUT), { recursive: true });
  writeFileSync(OUT, out);
  console.log(`build-brand-sprite: wrote ${glyphs.length} glyphs to ${OUT}`);
}

main();
